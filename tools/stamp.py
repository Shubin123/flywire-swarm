"""
Stamp index.html with a content hash so a deploy can never mix cached old files
with new ones (GitHub Pages serves everything with max-age=600).

Every local module, the stylesheet and the data files get ?v=<hash>; module
imports between our own files are remapped through the import map, and the
same hash is published in <meta name="build"> for data fetches and the worker.

Usage (from the repository root): python tools/stamp.py
"""
import hashlib
import json
import pathlib
import re

root = pathlib.Path(__file__).resolve().parent.parent
files = sorted([*root.glob("js/*.js"), *root.glob("css/*.css"), *root.glob("data/*")])
h = hashlib.sha1()
for f in files:
    h.update(f.name.encode())
    h.update(f.read_bytes())
v = h.hexdigest()[:10]

imports = {
    "three": "https://cdn.jsdelivr.net/npm/three@0.170.0/build/three.module.js",
    "three/addons/": "https://cdn.jsdelivr.net/npm/three@0.170.0/examples/jsm/",
}
for f in sorted(root.glob("js/*.js")):
    imports[f"./js/{f.name}"] = f"./js/{f.name}?v={v}"
importmap = json.dumps({"imports": imports}, indent=2).replace("\n", "\n  ")

block = f"""  <!-- build:start (generated by tools/stamp.py — run it before every deploy) -->
  <meta name="build" content="{v}" />
  <link rel="stylesheet" href="css/style.css?v={v}" />
  <script type="importmap">
  {importmap}
  </script>
  <link rel="modulepreload" href="https://cdn.jsdelivr.net/npm/three@0.170.0/build/three.module.js" />
  <link rel="preload" href="data/neurons.bin?v={v}" as="fetch" crossorigin />
  <link rel="preload" href="data/connectome.json?v={v}" as="fetch" crossorigin />
  <!-- build:end -->"""

html = (root / "index.html").read_text()
html = re.sub(r"  <!-- build:start.*?<!-- build:end -->", lambda m: block, html, flags=re.S)
html = re.sub(r'<script type="module" src="js/main\.js[^"]*" data-build-main>',
              f'<script type="module" src="js/main.js?v={v}" data-build-main>', html)
(root / "index.html").write_text(html)
print("stamped", v)
